def test_cli_exit_status_is_non_zero_and_stderr_names_the_key(tmp_path: Path) -> None:
    # The in-process tests see SystemExit; this one checks the status the
    # shell sees, which is what a Makefile or CI step would act on.
    findings_path = seed_findings(tmp_path)
    post_dir = seed_post_dir(tmp_path, part2="Worse: {{f.never_computed}} per cent.\n")
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), *cli_args(findings_path, post_dir)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 1
    assert "never_computed" in proc.stderr
    assert not (post_dir / "rendered-part1.md").exists()


def test_cli_exit_status_is_zero_on_a_clean_render(tmp_path: Path) -> None:
    findings_path = seed_findings(tmp_path)
    post_dir = seed_post_dir(tmp_path)
    proc = subprocess.run(
        [sys.executable, str(SCRIPT), *cli_args(findings_path, post_dir)],
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, proc.stderr
    assert "digit scan skips these tokens (ALLOWED_TOKENS): F1" in proc.stdout
    assert "draft-part1.md: 3 values substituted (3 distinct), 0 literals" in proc.stdout
    assert "draft-part2.md: 1 value substituted (1 distinct), 0 literals" in proc.stdout
    assert (post_dir / "claims-part1.md").read_text(encoding="utf-8") == GOLDEN_CLAIMS_PART1


