def test_claims_register_footnotes_the_ror_release_cited() -> None:
    """METHODS.md promises every institutional finding carries the ROR release;
    the published claims register has to show it, not just findings.json."""
    from disambig.findings import Finding
    from render_post import claims_table, render

    findings = {
        "coverage_n": Finding(
            value=12,
            unit="count",
            n=12,
            computed_by="scripts/x.py",
            computed_at="2026-10-01T12:00:00+00:00",
            source_snapshot="abc123def456789",
            ror_dump_version="v2.13",
        ),
        "kappa": Finding(
            value=0.8,
            unit="kappa",
            n=200,
            computed_by="scripts/y.py",
            computed_at="2026-10-01T12:00:00+00:00",
            source_snapshot="abc123def456789",
        ),
    }
    result = render("Coverage {{f.coverage_n}} and agreement {{f.kappa}}.", findings)
    table = claims_table(result, findings, "draft-part1.md", "findings.json")
    assert "ROR data dump release cited by the findings above: `v2.13`." in table
    assert "`kappa`" in table.split("ROR data dump release")[1]
