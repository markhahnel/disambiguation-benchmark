def test_literal_marker_renders_as_its_text_and_is_recorded_as_not_a_finding() -> None:
    findings = {"example_resolved_pct": make(42.0)}
    result = render(DRAFT_WITH_LITERAL, findings)
    assert result.text == "In 2026 the rate was 42.0 per cent.\n"
    assert not result.failed
    assert result.keys_used == ("example_resolved_pct",)  # the literal is not a key
    assert [(s.key, s.value) for s in result.substitutions] == [
        (None, "2026"),
        ("example_resolved_pct", "42.0"),
    ]
    assert [s.value for s in result.literals] == ["2026"]
    assert [s.key for s in result.finding_substitutions] == ["example_resolved_pct"]
    assert claims_table(result, findings, "draft.md", "findings.json") == (
        GOLDEN_CLAIMS_WITH_LITERAL
    )


